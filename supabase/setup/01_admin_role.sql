-- Step 1: メールアドレスを実際の管理者のメールアドレスに変更して実行してください
UPDATE auth.users
SET raw_app_meta_data = raw_app_meta_data || '{"role": "admin"}'::jsonb
WHERE email = 'your-admin@example.com';

-- Step 2: 設定が反映されたか確認
SELECT
  id,
  email,
  raw_app_meta_data ->> 'role' AS role,
  created_at
FROM auth.users
WHERE email = 'your-admin@example.com';

